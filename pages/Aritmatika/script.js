// operasi aritmatika

// ekspesi (expression) dan statement

// */+-
// $ <- modulo
// ++ increment
// -- decrement
// ** <- pangkat atau power

let x = 10
console.log(x + 1)
console.log(x - 1)
console.log(x / 4);
console.log(x * 2);

// aritmatika khusus di javascript
console.log(x % 3); // ini mengambil sisa dari pembagian

// aritmatika pemrogramman biasa
x = x + 1
console.log(x);
x = x + 1
console.log(x);

// menggunaka increment
x++
console.log(x);
x++
console.log(x);

// menggunakan decrement
x--
console.log(x);
x--
console.log(x);

// studi kasus
let y = 1 + '1' // akan menjadi string
console.log(y);
console.log(typeof y);

y = 1 + parseInt('1') // mengubah tipe string menjadi number
console.log(y);
console.log(typeof y);