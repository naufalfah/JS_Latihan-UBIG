// tipe data string
let dataString = "Naufal"
console.log(dataString);
console.log(typeof dataString);

// tipe data number
let dataNumber = 16.2345
console.log(dataNumber);
console.log(typeof dataNumber);

// tipe data boolean
let dataBoolean = false
console.log(dataBoolean);
console.log(typeof dataBoolean);

// ubah data string menjadi number
dataString = 2
console.log(dataString);
console.log(typeof dataString);

// data kosongan (undefined)
let dataKosong
console.log(dataKosong);
console.log(typeof dataKosong);

// isi data kosong dengan
dataKosong = "Ini bukan data kosong"
console.log(dataKosong);
console.log(typeof dataKosong);